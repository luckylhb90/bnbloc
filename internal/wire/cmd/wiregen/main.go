// Command wiregen writes web/src/lib/wire.gen.ts, the TypeScript mirror of
// the JSON the web client exchanges with the server. Every line of it comes
// from a Go owner, never from a second hand-written copy:
//
//   - every exported type, constant and constant-valued variable of
//     internal/wire (a struct is an interface, `omitempty` an optional
//     field, an embedded struct `extends`, a named string type the union of
//     its constants, a variable holding only constants a readonly value);
//   - `//wire:union <Name>` on a block (or one spec) of untyped constants:
//     the union of their values, collected across files (the room event
//     kinds);
//   - enums owned by other packages (store.AgentJobStatus, store.Role, …),
//     which a wire field names with a `tstype:"<Name>"` tag;
//   - tables the owners compute at generation time (the org role grants of
//     rbac.Can, the job statuses store.AgentJobStatus.Terminal reports done,
//     the room roles store.Role.CanInvite admits).
//
// Regenerate with `go generate ./internal/wire`. `scripts/ci.sh go` runs
// `go run ./internal/wire/cmd/wiregen -check`, which fails on drift.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

// output is the generated file, relative to the module root.
const output = "web/src/lib/wire.gen.ts"

func main() {
	check := flag.Bool("check", false, "fail (exit 1) when "+output+" differs from what would be generated, instead of writing it")
	flag.Parse()
	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}
	src, err := generate(root)
	if err != nil {
		fatal(err)
	}
	path := filepath.Join(root, output)
	if *check {
		have, err := os.ReadFile(path)
		if err != nil {
			fatal(err)
		}
		if !bytes.Equal(have, src) {
			fatal(fmt.Errorf("%s is out of date with internal/wire; run `go generate ./internal/wire` and commit the result", output))
		}
		return
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		fatal(err)
	}
}

// generate renders the whole file.
func generate(root string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/wire/cmd/wiregen; DO NOT EDIT.\n")
	b.WriteString("// The JSON shapes, constants and rule tables the web shares with the Go\n")
	b.WriteString("// server. Regenerate: go generate ./internal/wire (scripts/ci.sh go fails on drift).\n")
	enums, err := externalEnums(root)
	if err != nil {
		return nil, err
	}
	enums = append(enums, registryEnums()...)
	pkg, err := emitPackage(filepath.Join(root, "internal", "wire"), "github.com/luckylhb90/bnbloc/internal/wire", enums.names())
	if err != nil {
		return nil, err
	}
	b.Write(pkg)
	b.Write(enums.render())
	tables, err := ownerTables(enums)
	if err != nil {
		return nil, err
	}
	b.Write(tables)
	return b.Bytes(), nil
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("wiregen: no go.mod above the working directory")
		}
		dir = parent
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "wiregen:", err)
	os.Exit(1)
}
